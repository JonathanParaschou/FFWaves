"""Make normalized browser MP3s from the preserved original Ogg recordings.

Developer-only dependencies: numpy, soundfile, lameenc. No runtime dependencies.
"""
from pathlib import Path
import hashlib
import json
import lameenc
import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'dist/assets/music-original'
catalog_path = OUT / 'catalog.json'
catalog = json.loads(catalog_path.read_text())
tracks = {}
for key, entry in catalog['tracks'].items():
    samples, rate = sf.read(ROOT / 'dist' / entry['url'], always_2d=True)
    rms = float(np.sqrt(np.mean(samples * samples)))
    peak = float(np.max(np.abs(samples)))
    gain = min(.126 / max(rms, .00001), .88 / max(peak, .00001))
    pcm = np.clip(samples * gain * 32767, -32768, 32767).astype('<i2')
    encoder = lameenc.Encoder()
    encoder.set_bit_rate(128)
    encoder.set_in_sample_rate(rate)
    encoder.set_channels(samples.shape[1])
    encoder.set_quality(2)
    data = encoder.encode(pcm.tobytes()) + encoder.flush()
    name = key + '.mp3'
    (OUT / name).write_bytes(data)
    decoded, decoded_rate = sf.read(OUT / name, always_2d=True)
    assert abs(len(decoded) / decoded_rate - len(samples) / rate) < .2
    playback = {'url': 'assets/music-original/' + name, 'mime': 'audio/mpeg',
                'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
                'gain': round(gain, 5), 'rmsDb': round(20 * np.log10(np.sqrt(np.mean(decoded ** 2))), 2)}
    entry['playback'] = playback
    tracks[key] = {'title': entry['title'], 'url': playback['url']}
    print(key, len(data), playback['rmsDb'], 'dB RMS')
catalog['playbackProcessing'] = 'Original recordings decoded, peak-limited RMS gain applied, LAME MP3 128 kbps. Original Ogg bytes preserved.'
catalog_path.write_text(json.dumps(catalog, indent=2) + '\n')
(ROOT / 'dist/music-tracks.js').write_text('// Generated by tools/prepare-browser-music.py; original FusionFall recordings.\nexport const MUSIC_TRACKS=' + json.dumps(tracks, separators=(',', ':')) + ';\n')
